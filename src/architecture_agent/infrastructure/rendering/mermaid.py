"""Mermaid renderer.

Covers the diagram kinds that can be derived from an :class:`Architecture` without
further information: C4 context, container, component and code views, plus class,
sequence and component views.

Syntax is validated by :mod:`architecture_agent.infrastructure.rendering.syntax`
before the source is returned, so a renderer bug surfaces as a failed tool call
rather than as a broken diagram in the client's editor.
"""

from __future__ import annotations

from collections.abc import Sequence

from architecture_agent.domain.architecture import Architecture, ComponentKind
from architecture_agent.domain.diagram import DiagramKind, ValidationSeverity
from architecture_agent.domain.infrastructure import InfrastructurePlan, NetworkTier
from architecture_agent.infrastructure.rendering.identifiers import (
    IdentifierMap,
    sanitize_label,
)
from architecture_agent.infrastructure.rendering.syntax import MERMAID, find_issues

_C4_KIND_BY_DIAGRAM: dict[DiagramKind, str] = {
    DiagramKind.C4_CONTEXT: "C4Context",
    DiagramKind.C4_CONTAINER: "C4Container",
    DiagramKind.C4_COMPONENT: "C4Component",
    DiagramKind.C4_CODE: "C4Code",
}

_MERMAID_DIRECTIVE_BY_DIAGRAM: dict[DiagramKind, str] = {
    DiagramKind.CLASS: "classDiagram",
    DiagramKind.SEQUENCE: "sequenceDiagram",
    DiagramKind.COMPONENT: "flowchart LR",
    DiagramKind.DEPLOYMENT: "flowchart TB",
    DiagramKind.ER: "erDiagram",
    DiagramKind.FLOWCHART: "flowchart TD",
    DiagramKind.NETWORK_TOPOLOGY: "flowchart LR",
}

_SUPPORTED_KINDS: frozenset[DiagramKind] = frozenset(
    set(_C4_KIND_BY_DIAGRAM) | set(_MERMAID_DIRECTIVE_BY_DIAGRAM)
)


class MermaidRenderer:
    """Render an architecture as Mermaid source.

    Satisfies the ``DiagramRenderer`` port declared by the diagram use case.
    """

    language = "mermaid"
    supported_kinds: frozenset[DiagramKind] = _SUPPORTED_KINDS

    def supports(self, kind: DiagramKind) -> bool:
        """Whether this renderer can produce ``kind``."""
        return kind in self.supported_kinds

    def render(
        self,
        architecture: Architecture,
        kind: DiagramKind,
        *,
        plan: InfrastructurePlan | None = None,
    ) -> tuple[str, tuple[str, ...]]:
        """Render ``architecture`` and return the source plus sanitisation warnings.

        Warnings name the labels that were altered, so a caller can tell the user
        the diagram is not a faithful reproduction of the input.
        """
        if not self.supports(kind):
            msg = f"Mermaid cannot render {kind.value}"
            raise ValueError(msg)

        warnings: list[str] = []
        if kind in _C4_KIND_BY_DIAGRAM:
            source = self._render_c4(architecture, kind, warnings)
        elif kind is DiagramKind.CLASS:
            source = self._render_class(architecture, warnings)
        elif kind is DiagramKind.SEQUENCE:
            source = self._render_sequence(architecture, warnings)
        elif kind is DiagramKind.NETWORK_TOPOLOGY and plan is not None:
            source = self._render_network(plan, warnings)
        else:
            source = self._render_flowchart(architecture, kind, warnings)

        issues = find_issues(source, MERMAID)
        blocking = [issue for issue in issues if issue.severity is ValidationSeverity.ERROR]
        if blocking:
            msg = f"generated Mermaid is not valid: {blocking[0]}"
            raise ValueError(msg)

        return source, tuple(warnings)

    def _render_c4(self, architecture: Architecture, kind: DiagramKind, warnings: list[str]) -> str:
        directive = _C4_KIND_BY_DIAGRAM[kind]
        title, notes = _label(architecture.name)
        warnings.extend(notes)
        lines = [
            directive,
            f"  title {title}",
            "  %% generated by architecture-agent; identifiers are positional",
        ]

        if kind is DiagramKind.C4_CONTEXT:
            for dependency in architecture.external_dependencies:
                label, notes = _label(dependency.name)
                warnings.extend(notes)
                lines.append(f'  System_Ext(alias, "{label}", "{label}")')
            return "\n".join(lines)

        aliases = IdentifierMap.assign([component.name for component in architecture.components])
        for component in architecture.components:
            label, notes = _label(component.name)
            warnings.extend(notes)
            lines.append(
                f'  Container({aliases.alias(component.name)}, "{label}", '
                f'"{_technology_summary(component.technology)}")'
            )

        for interaction in architecture.interactions:
            protocol, notes = _label(interaction.protocol)
            warnings.extend(notes)
            source = aliases.alias(interaction.source)
            target = aliases.alias(interaction.target)
            lines.append(f'  Rel({source}, {target}, "{protocol}")')

        if kind in {DiagramKind.C4_CONTAINER, DiagramKind.C4_COMPONENT, DiagramKind.C4_CODE}:
            for index, dependency in enumerate(architecture.external_dependencies, start=1):
                label, notes = _label(dependency.name)
                warnings.extend(notes)
                lines.append(f'  System_Ext(ext{index}, "{label}", "{label}")')

        return "\n".join(lines)

    def _render_class(self, architecture: Architecture, warnings: list[str]) -> str:
        aliases = IdentifierMap.assign([component.name for component in architecture.components])
        lines = ["classDiagram", "  direction LR"]

        for component in architecture.components:
            alias = aliases.alias(component.name)
            label, notes = _label(component.name)
            warnings.extend(notes)
            stereotype = _stereotype(component.kind)
            lines.append(f'  class {alias}["{label}"] {{ {stereotype} }}')
            for technology in component.technology:
                safe, notes = _label(technology[:40])
                warnings.extend(notes)
                lines.append(f"  class {alias} : {safe}")

        for interaction in architecture.interactions:
            protocol, notes = _label(interaction.protocol)
            warnings.extend(notes)
            source = aliases.alias(interaction.source)
            target = aliases.alias(interaction.target)
            arrow = "-->" if interaction.synchronous else "-.->"
            lines.append(f"  {source} {arrow} {target} : {protocol}")

        return "\n".join(lines)

    def _render_sequence(self, architecture: Architecture, warnings: list[str]) -> str:
        aliases = IdentifierMap.assign([component.name for component in architecture.components])
        lines = ["sequenceDiagram", "    autonumber"]

        for component in architecture.components:
            label, notes = _label(component.name)
            warnings.extend(notes)
            lines.append(f"    participant {aliases.alias(component.name)} as {label}")

        for interaction in architecture.interactions:
            arrow = "->>" if interaction.synchronous else "-->>"
            protocol, notes = _label(interaction.protocol[:40])
            warnings.extend(notes)
            lines.append(
                f"    {aliases.alias(interaction.source)} {arrow} "
                f"{aliases.alias(interaction.target)}: {protocol}"
            )

        return "\n".join(lines)

    def _render_network(self, plan: InfrastructurePlan, warnings: list[str]) -> str:
        aliases = IdentifierMap.assign([segment.name for segment in plan.network])
        lines = ["flowchart LR", "    %% subnet layout with exposure tiers"]

        for segment in plan.network:
            label, notes = _label(f"{segment.name} - {segment.tier.value}")
            warnings.extend(notes)
            exposure = "public" if segment.public else "private"
            lines.append(f'    {aliases.alias(segment.name)}["{label} {segment.cidr} {exposure}"]')

        for position, database in enumerate(plan.databases, start=1):
            alias = f"db{position}"
            label, notes = _label(f"{database.name} - {database.engine.value}")
            warnings.extend(notes)
            lines.append(f'    {alias}["{label} {database.topology.value}"]')
            for segment in plan.segment_for_tier(NetworkTier.DATA):
                lines.append(f"    {aliases.alias(segment.name)} -.-> {alias}")

        return "\n".join(lines)

    def _render_flowchart(
        self, architecture: Architecture, kind: DiagramKind, warnings: list[str]
    ) -> str:
        directive = _MERMAID_DIRECTIVE_BY_DIAGRAM[kind]
        aliases = IdentifierMap.assign([component.name for component in architecture.components])
        lines = [directive]

        for component in architecture.components:
            label, notes = _label(f"{component.name} - {component.kind.value}")
            warnings.extend(notes)
            lines.append(f'    {aliases.alias(component.name)}["{label}"]')

        for interaction in architecture.interactions:
            style = "-->" if interaction.synchronous else "-.->"
            source = aliases.alias(interaction.source)
            target = aliases.alias(interaction.target)
            lines.append(f"    {source} {style} {target}")

        return "\n".join(lines)


def _label(text: str) -> tuple[str, list[str]]:
    """Sanitise ``text`` for diagram syntax and report whether it changed.

    Composed labels must be built from characters the sanitiser preserves, or
    every render would raise a warning about a separator the renderer chose
    itself. The helper exists so the comparison is always between a sanitiser's
    input and its output.
    """
    sanitized = sanitize_label(text)
    if not sanitized.modified:
        return sanitized.value, []
    return sanitized.value, [
        f"label sanitised for diagram syntax: {text.strip()[:80]!r} -> {sanitized.value!r}"
    ]


def _technology_summary(technology: Sequence[str]) -> str:
    """Collapse a technology list into one C4 technology label."""
    if not technology:
        return "Technology not specified"
    return sanitize_label(", ".join(technology[:4])[:60]).value


def _stereotype(kind: ComponentKind) -> str:
    """Map a component kind to a UML stereotype."""
    mapping = {
        ComponentKind.CLIENT: "actor",
        ComponentKind.SERVICE: "component",
        ComponentKind.API: "interface",
        ComponentKind.DATABASE: "database",
        ComponentKind.CACHE: "component",
        ComponentKind.QUEUE: "component",
        ComponentKind.EXTERNAL: "component",
    }
    return mapping.get(kind, "component")
